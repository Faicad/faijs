    const { a, b } = splitHashEvolutionByOrigin(evo, hashesA, hashesB)

    expect([...a.modified.keys()].sort()).toEqual([hashesA[4], hashesA[5]].sort())
    const toolSide = hashesB.find((h) => /cylind/i.test(typeOf(tool, h)))!
    expect([...b.modified.keys()]).toEqual([toolSide])
    expect([...a.deleted]).toEqual([])
