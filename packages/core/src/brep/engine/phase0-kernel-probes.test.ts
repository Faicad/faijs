    const names = allPropertyNames(kernel)
    const historyFamily = names.filter((n) => n.endsWith('WithHistory')).sort()

    // 负向完整性：族里只有这 12 个（内核多出成员 ⇒ 本断言变红 ⇒ 重评第 1 项分支）
    expect(historyFamily).toEqual([...ALL_WITH_HISTORY].sort())

