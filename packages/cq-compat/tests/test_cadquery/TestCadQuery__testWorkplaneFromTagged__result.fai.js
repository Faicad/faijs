import * as cq from '@faicad/cq-compat'
let wp0 = cq.Workplane('XY')
let wp1 = await cq.box(wp0, 10, 10, 1, { centered: [true, true, false] })
let wp2 = cq.faces(wp1, '>Z')
let wp3 = await cq.workplane(wp2)
let tagged = cq.tag(wp3, 'base')
let wp4 = await cq.center(tagged, 3, 0)
let wp5 = await cq.rect(wp4, 2, 2)
let wp6 = await cq.extrude(wp5, 4)
let wp7 = cq.faces(wp6, '>Z')
let wp8 = await cq.workplane(wp7)
let wp9 = await cq.circle(wp8, 1)
let wp10 = await cq.extrude(wp9, 6)
let back = cq.workplaneFromTagged(wp10, 'base')
let wp11 = await cq.center(back, -3, 0)
let wp12 = await cq.circle(wp11, 1)
let result = await cq.extrude(wp12, 11)
let resultVal = cq.val(result)
