/**
 * check-lockstep — faijs package-family lockstep guard (enforcement half).
 *
 * Two rules over the publishable `@faicad/*` family:
 *
 *   1. **version equality** — every family member's `version` equals the root
 *      `package.json` `config.faijsVersion` (the single source of truth). The family
 *      publishes under one version, so a member drifting onto a private version line
 *      silently forks the release.
 *   2. **range coherence** — every registry-range (`^…`) `@faicad/*` entry in
 *      dependencies / peerDependencies / devDependencies equals `^<major>.<minor>.0`
 *      of the target package. `file:` / `workspace:` / `link:` entries are local
 *      resolutions and are skipped.
 *   3. **CDN pin coherence** — `cdn/versions.json` (the plan-b exact-pin release
 *      mirror, generated by `gen-importmap.mjs`) pins every *publishable* family
 *      member at its current version. Private packages are exempt: they are never
 *      published, so the mirror has (and must not have) a pin for them. Skipped
 *      when the file is absent.
 *
 * Rule 2 exists because of a 2026-09 incident: `faijs-gears` had bumped itself to
 * 0.16.x while its `dependencies` still declared `"@faicad/faijs-cadquery": "^0.14.0"`, so
 * the CDN build resolved a stale `cq-compat@0.14.1` whose pinned `@faicad/faijs`
 * broke the package graph. Rule 1 alone cannot catch a stale range; rule 2 alone
 * cannot catch a forked version line. Both run. Rule 3 exists because the mirror is
 * a second home for the same fact and had drifted three version lines behind.
 *
 * Usage: node scripts/check-lockstep.mjs [--include-private] [--self-test]
 * Exit code: 0 = pass; 1 = violations found.
 */
import {
  collectViolations,
  familyVersion,
  readCdnVersions,
  readFamily,
  readRootPackage,
} from './lockstep-lib.mjs'

const includePrivate = process.argv.includes('--include-private')

/**
 * Rule-engine self-test. The guard runs on every commit and every CI build, so a
 * silently broken rule engine would let drift through unnoticed; these cases pin
 * the pass/fail boundary on synthetic package sets.
 * @returns {string[]} failed case descriptions, empty when all cases behave
 */
function selfTest() {
  const mk = (name, version, sections = {}) => [name, { name, version, pj: { name, version, ...sections } }]
  const cases = [
    {
      title: 'aligned family passes',
      family: new Map([
        mk('@faicad/faijs', '0.20.0'),
        mk('@faicad/faijs-extra', '0.20.0', { peerDependencies: { '@faicad/faijs': '^0.20.0' } }),
      ]),
      declared: '0.20.0',
      expect: 0,
    },
    {
      title: 'forked version line is caught',
      family: new Map([mk('@faicad/faijs', '0.20.0'), mk('@faicad/faijs-draw', '0.18.3')]),
      declared: '0.20.0',
      expect: 1,
    },
    {
      title: 'stale dependency range is caught',
      family: new Map([
        mk('@faicad/faijs', '0.20.0'),
        mk('@faicad/faijs-gears', '0.20.0', { dependencies: { '@faicad/faijs': '^0.14.0' } }),
      ]),
      declared: '0.20.0',
      expect: 1,
    },
    {
      title: 'local file: range is not constrained',
      family: new Map([
        mk('@faicad/faijs', '0.20.0'),
        mk('@faicad/faijs-freecad', '0.20.0', { dependencies: { '@faicad/faijs': 'file:../core' } }),
      ]),
      declared: '0.20.0',
      expect: 0,
    },
    {
      title: 'external @faicad-looking name is not constrained',
      family: new Map([
        mk('@faicad/faijs', '0.20.0'),
        mk('@faicad/other-repo-pkg', '0.20.0', { dependencies: { '@faicad/not-in-family': '^0.9.0' } }),
      ]),
      declared: '0.20.0',
      expect: 0,
    },
    {
      title: 'missing family version declaration is caught',
      family: new Map([mk('@faicad/faijs', '0.20.0')]),
      declared: null,
      expect: 1,
    },
    {
      title: 'devDependencies ranges are covered too',
      family: new Map([
        mk('@faicad/faijs', '0.20.0'),
        mk('@faicad/faijs-sketch', '0.20.0', { devDependencies: { '@faicad/faijs': '^0.19.0' } }),
      ]),
      declared: '0.20.0',
      expect: 1,
    },
    {
      title: 'stale cdn/versions.json pin is caught',
      family: new Map([mk('@faicad/faijs', '0.20.0')]),
      declared: '0.20.0',
      cdn: { '@faicad/faijs': '0.16.2' },
      expect: 1,
    },
    {
      title: 'family member missing from cdn/versions.json is caught',
      family: new Map([mk('@faicad/faijs', '0.20.0'), mk('@faicad/faijs-draw', '0.20.0')]),
      declared: '0.20.0',
      cdn: { '@faicad/faijs': '0.20.0' },
      expect: 1,
    },
    {
      title: 'absent cdn mirror is skipped',
      family: new Map([mk('@faicad/faijs', '0.20.0')]),
      declared: '0.20.0',
      cdn: null,
      expect: 0,
    },
    {
      // GOTCHA: `--include-private` must NOT widen rule 3. gen-importmap.mjs skips
      // `private: true` packages, so cdn/versions.json has no pin for them, and a
      // pin would be a URL that does not exist. Before this case existed the guard
      // demanded an impossible pin and went permanently red once the private
      // packages joined the family version line.
      title: 'private family member needs no cdn pin',
      family: new Map([
        mk('@faicad/faijs', '0.20.0'),
        [
          '@faicad/faijs-tests',
          {
            name: '@faicad/faijs-tests',
            version: '0.20.0',
            private: true,
            pj: { name: '@faicad/faijs-tests', version: '0.20.0' },
          },
        ],
      ]),
      declared: '0.20.0',
      cdn: { '@faicad/faijs': '0.20.0' },
      expect: 0,
    },
    {
      title: 'private family member is still version-checked',
      family: new Map([
        mk('@faicad/faijs', '0.20.0'),
        [
          '@faicad/faijs-tests',
          {
            name: '@faicad/faijs-tests',
            version: '0.5.9',
            private: true,
            pj: { name: '@faicad/faijs-tests', version: '0.5.9' },
          },
        ],
      ]),
      declared: '0.20.0',
      cdn: { '@faicad/faijs': '0.20.0' },
      expect: 1,
    },
  ]

  const failed = []
  for (const c of cases) {
    const got = collectViolations(c.family, c.declared, c.cdn ?? null).length
    if (got !== c.expect) {
      failed.push(`${c.title}: expected ${c.expect} violation(s), got ${got}`)
    }
  }
  return failed
}

if (process.argv.includes('--self-test')) {
  const failed = selfTest()
  if (failed.length > 0) {
    console.error(`[check-lockstep] self-test FAILED (${failed.length}):`)
    for (const f of failed) console.error('  ' + f)
    process.exit(1)
  }
  console.log('[check-lockstep] self-test OK')
}

const family = readFamily({ includePrivate })
if (family.size === 0) {
  console.error('[check-lockstep] no @faicad/* packages found under packages/')
  process.exit(1)
}

const declared = familyVersion(readRootPackage())
const violations = collectViolations(family, declared, readCdnVersions())

if (violations.length > 0) {
  console.error(`[check-lockstep] ${violations.length} violation(s):`)
  for (const v of violations) console.error('  ' + v)
  process.exit(1)
}

const label = includePrivate ? 'workspace packages' : 'publishable family packages'
console.log(
  `[check-lockstep] OK — ${family.size} ${label} at ${declared}, all @faicad/* dep ranges on the family version line`,
)
